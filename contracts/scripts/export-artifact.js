/**
 * Copies the compiled TraceAnchor ABI + bytecode to where the apps use them:
 *   backend/src/anchor/TraceAnchor.artifact.json  — worker (submit) and the
 *                                                  local-chain deploy script
 *   frontend/src/lib/verify/traceAnchorAbi.ts     — browser verifier (read-only ABI)
 * Run after `npm run compile` whenever the contract changes.
 */
const fs = require('fs');
const path = require('path');

const artifact = require('../artifacts/contracts/TraceAnchor.sol/TraceAnchor.json');
const root = path.resolve(__dirname, '..', '..');

const backendOut = path.join(root, 'backend', 'src', 'anchor', 'TraceAnchor.artifact.json');
fs.mkdirSync(path.dirname(backendOut), { recursive: true });
fs.writeFileSync(
  backendOut,
  JSON.stringify({ contractName: artifact.contractName, abi: artifact.abi, bytecode: artifact.bytecode }, null, 2) + '\n',
);

const readOnly = artifact.abi.filter((item) => item.type === 'function' && item.stateMutability === 'view');
const frontendOut = path.join(root, 'frontend', 'src', 'lib', 'verify', 'traceAnchorAbi.ts');
fs.mkdirSync(path.dirname(frontendOut), { recursive: true });
fs.writeFileSync(
  frontendOut,
  '// Generated by contracts/scripts/export-artifact.js — do not edit by hand.\n' +
    `export const traceAnchorAbi = ${JSON.stringify(readOnly, null, 2)} as const\n`,
);

console.log(`Wrote ${path.relative(root, backendOut)} and ${path.relative(root, frontendOut)}`);
